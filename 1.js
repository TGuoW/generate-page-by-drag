// 1.js - 简单的 JavaScript 文件

// 函数示例
function greet(name) {
  return `Hello, ${name}!`;
}

// 变量示例
const message = "Welcome to JavaScript!";

// 数组示例
const fruits = ['apple', 'banana', 'orange'];

// 对象示例
const person = {
  name: 'John',
  age: 30,
  profession: 'Developer'
};

// 循环示例
console.log('Fruits:');
fruits.forEach(fruit => {
  console.log(fruit);
});

// 输出示例
console.log(greet('World'));
console.log(message);
console.log('Person:', person);
